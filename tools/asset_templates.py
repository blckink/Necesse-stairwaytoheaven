# mob: walking, 4-direction

def template_mob(cell=64):
    """6 cols x 4 rows of `cell`, then a 32px GIB STRIP, then 32px of padding.

    Rows are Up/Right/Down/Left -- VERIFIED in docs/research/asset-formats.md 5,
    resolved there from the Mob class rather than from the wiki, which had it
    wrong.

    The gib strip is not folklore either: mobs spawn death chunks with
    `new FleshParticle(level, texture, spriteX, 8, 32, ...)` -- sprite column
    spriteX, ROW 8 in 32px units (y256..288), 32px cells, spriteX drawn from
    `nextInt(5)` or a `for i < 4` loop. VERIFIED [jar] in CrystalGolemMob,
    BloatedSpiderMob, ChickenRaiderMob, AncientSkeletonRaiderMob.

    Measured on vanilla crystalgolem, bloatedspider and our own crookedgolem:
    all three are 384x320, all three fill y256..288 in the first 3-4 columns
    only, and all three leave y288..320 completely empty.
    """
    zoom = 3
    art_w, art_h = cell * 6, cell * 4 + 64
    ref = os.path.join(REPO, "src/main/resources/mobs/crookedgolem.png")
    have_ref = os.path.exists(ref) and Image.open(ref).size == (art_w, art_h)
    img = canvas(art_w, art_h, 660, 300, zoom, ref if have_ref else None)
    d = ImageDraw.Draw(img)
    font, font_sm, font_big = fonts()
    cols = ("idle", "walk 1", "walk 2", "walk 3", "walk 4", "in liquid")
    rows = ("UP\n(back)", "RIGHT\n(side)", "DOWN\n(front)", "LEFT\n(side)")
    for r in range(4):
        for c in range(6):
            x0, y0 = c * cell * zoom, r * cell * zoom
            box = (x0, y0, x0 + cell * zoom - 1, y0 + cell * zoom - 1)
            tint(img, box, CO_A if c in (0, 5) else CO_B, 40)
            d.rectangle(box, outline=GRID)
            d.text((x0 + 6, y0 + 4), cols[c], fill=(255, 255, 255), font=font)
            yy = y0 + 24
            for line in rows[r].split("\n"):
                d.text((x0 + 6, yy), line, fill=(235, 235, 240), font=font_sm)
                yy += 14
            d.text((x0 + 6, y0 + cell * zoom - 20), "%dx%d" % (cell, cell),
                   fill=(190, 190, 200), font=font_sm)
    d.rectangle((5 * cell * zoom, 0, 6 * cell * zoom - 1, 4 * cell * zoom - 1),
                outline=CO_C, width=3)
    # the gib strip and the padding row, both in 32px units
    gy = 4 * cell * zoom
    for c in range(12):
        x0 = c * 32 * zoom
        box = (x0, gy, x0 + 32 * zoom - 1, gy + 32 * zoom - 1)
        if c < 5:
            tint(img, box, CO_D, 60)
            d.text((x0 + 4, gy + 4), "gib %d" % c, fill=(255, 225, 255), font=font_sm)
        d.rectangle(box, outline=GRID)
    d.rectangle((0, gy, 5 * 32 * zoom - 1, gy + 32 * zoom - 1), outline=CO_D, width=3)
    d.text((5 * 32 * zoom + 8, gy + 6), "DEATH CHUNKS: 32px cells, up to 5 of them",
           fill=(255, 200, 255), font=font)
    d.text((5 * 32 * zoom + 8, gy + 26), "(FleshParticle reads sprite row 8)",
           fill=(255, 200, 255), font=font_sm)
    py = gy + 32 * zoom
    d.rectangle((0, py, art_w * zoom - 1, art_h * zoom - 1), outline=(140, 140, 150), width=2)
    d.text((8, py + 8), "unused padding - vanilla leaves this row empty",
           fill=(190, 190, 200), font=font)

    legend = ["Cell %dpx. 6 columns x 4 rows," % cell,
              "then a 32px gib strip, then padding.",
              "",
              "col  0     idle / standing",
              "cols 1-4   the walk cycle, in order",
              "col  5     drawn while in liquid (cyan):",
              "           same pose, lower body cut off",
              "           at the surface line",
              "",
              "rows       UP, RIGHT, DOWN, LEFT - in THAT",
              "           order. Not compass order.",
              "",
              "y256-288   death chunks, 32px cells",
              "y288-320   unused, leave empty",
              "",
              "LEFT is not a free mirror of RIGHT: the",
              "engine does not flip. Draw it, or paste",
              "RIGHT mirrored and redo the shading -",
              "light always comes from the top-left.",
              "",
              "Optional companions, same grid:",
              "  mobs/<id>_light.png    glow pass",
              "  mobs/<id>_shadow.png   4 cols x 1 row",
              "  mobs/icons/<id>.png    32x32 bestiary"]
    rules = ["ANCHORING: feet near the bottom of the cell, sprite centred horizontally.",
             "Match the mass of a vanilla mob of the same role -- tools/size_audit.py compares you against one and a",
             "FIX flag blocks shipping. Necesse mobs are CHUNKY: big head, silhouette readable at 1x.",
             "",
             "Background fully transparent. Soft dark outline (34,34,46) around the body, never pure black."]
    if have_ref:
        rules.append("The art behind this template is our own crookedgolem sheet, for mass and framing reference.")
    finish(img, d, "MOB SHEET (walking, 4-dir)  %dx%d" % (art_w, art_h),
           legend, rules, art_w, art_h, zoom, font, font_big)
    return img, "mob"


