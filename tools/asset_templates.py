# object + item

def template_object():
    """32*cols x 32*rows, bottom-anchored in the sorted layer. VERIFIED in
    docs/research/asset-formats.md 3 and its summary table."""
    zoom = 4
    art_w, art_h = 32 * 4, 32 * 4
    img = canvas(art_w, art_h, 700, 460, zoom)
    d = ImageDraw.Draw(img)
    font, font_sm, font_big = fonts()
    for c in range(4):
        x0 = c * 32 * zoom
        d.rectangle((x0, 0, x0 + 32 * zoom - 1, art_h * zoom - 1), outline=CO_B, width=3)
        d.text((x0 + 6, 6), "variant %d" % c, fill=(255, 220, 170), font=font)
    for r in range(4):
        y0 = r * 32 * zoom
        d.rectangle((0, y0, art_w * zoom - 1, y0 + 32 * zoom - 1), outline=GRID)
        d.text((6, y0 + 32 * zoom - 20),
               "row %d  (%s)" % (r, "the object's OWN tile" if r == 3
                                 else "%d tile(s) of height above it" % (3 - r)),
               fill=(235, 235, 240), font=font_sm)
    d.rectangle((0, 3 * 32 * zoom, art_w * zoom - 1, art_h * zoom - 1),
                outline=CO_C, width=4)
    finish(img, d, "OBJECT SHEET  32*variants wide x 32*N tall",
           ["Width  = 32 x however many random variants",
            "Height = 32 x how tall the thing is",
            "",
            "BOTTOM-ANCHORED (sorted layer): the LAST",
            "32px row is the tile the object stands on",
            "(cyan). Everything above it rises into the",
            "tiles behind, drawn in front of them.",
            "",
            "Top-anchored instead (tile-decal layer)",
            "for flat things -- carpets, floor marks.",
            "",
            "Shipped examples, all real sizes:",
            "  items/skyreave.png        32x32",
            "  objects/skyanchor.png     32x64",
            "  objects/statues/...       64x96",
            "  objects/mistglasslantern  64x128",
            "  objects/wardencandelabra  32x192",
            "",
            "A holdable object ALSO needs a 32x32",
            "icon at items/<id>.png."],
           ["VARIANTS ARE NOT OPTIONAL DECORATION. A ground scattered with one silhouette reads as a grid of",
            "stamps. Vanilla ships 4-8 variants for anything common; 2 is the floor for anything rare.",
            "",
            "Light from the TOP-LEFT, 2-4 flat shade steps, soft dark outline (34,34,46) -- never pure black.",
            "Silhouette has to read at 1x against BOTH a light ground (cloudturf) and a dark one (stormslate)."],
           art_w, art_h, zoom, font, font_big)
    return img, "object"


def template_item():
    """32x32 icon. Summary table: "items/<stringid>.png, 32x32 recommended"."""
    zoom = 10
    art_w = art_h = 32
    img = canvas(art_w, art_h, 700, 420, zoom)
    d = ImageDraw.Draw(img)
    font, font_sm, font_big = fonts()
    for i in range(0, 33, 4):
        d.line((i * zoom, 0, i * zoom, art_h * zoom), fill=(255, 255, 255, 40))
        d.line((0, i * zoom, art_w * zoom, i * zoom), fill=(255, 255, 255, 40))
    # the safe area vanilla icons keep to
    d.rectangle((2 * zoom, 2 * zoom, 30 * zoom - 1, 30 * zoom - 1), outline=CO_C, width=3)
    d.text((2 * zoom + 6, 2 * zoom + 4), "keep inside: 28x28", fill=(190, 245, 230), font=font)
    d.rectangle((6 * zoom, 2 * zoom, 26 * zoom - 1, 30 * zoom - 1), outline=CO_B, width=2)
    d.text((6 * zoom + 6, 30 * zoom - 24), "tools sit in this 20x28", fill=(255, 220, 170), font=font_sm)
    finish(img, d, "ITEM ICON  32x32",
           ["One object, centred, filling the frame.",
            "",
            "Vanilla icons are NOT shrunken world",
            "sprites -- they are drawn for the slot:",
            "a tree's icon is a compact glyph, not the",
            "128x1024 world sheet scaled down.",
            "",
            "Cyan  28x28 safe area (2px margin all",
            "      round so the UI's hover ring and",
            "      the stack count do not clip it).",
            "Amber the narrower box tools/weapons use:",
            "      they read as a diagonal from the",
            "      bottom-left to the top-right.",
            "",
            "Straight alpha. No drop shadow, no glow,",
            "no background plate."],
           ["Every holdable thing needs one, or it shows the pink ERROR texture in the inventory.",
            "tools/locale_audit.py fails the build when a registered holdable ID has no items/<id>.png.",
            "",
            "Same palette discipline as the world sprite: light top-left, 2-4 flat steps, soft dark outline."],
           art_w, art_h, zoom, font, font_big)
    return img, "item"


BUILDERS = {
    "mob": template_mob,
    "splat": template_splat,
    "object": template_object,
    "item": template_item,
}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--class", dest="klass", default=None,
                    help="one of: " + ", ".join(sorted(BUILDERS)) + " (default: all)")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()
    if args.list:
        print("classes:", ", ".join(sorted(BUILDERS)))
        print("wall: generated by tools/wall_template_map.py (roles enumerated "
              "from the engine port)")
        return
    names = [args.klass] if args.klass else sorted(BUILDERS)
    os.makedirs(OUT_QA, exist_ok=True)
    os.makedirs(OUT_DOCS, exist_ok=True)
    for name in names:
        if name not in BUILDERS:
            raise SystemExit("unknown class %r; --list to see them" % name)
        img, slug = BUILDERS[name]()
        p = os.path.join(OUT_QA, "template-%s.png" % slug)
        img.save(p)
        img.save(os.path.join(OUT_DOCS, "template-%s.png" % slug))
        print("wrote %s  %s" % (p, img.size))


if __name__ == "__main__":
    main()
