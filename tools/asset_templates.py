#!/usr/bin/env python3
"""Labelled drawing templates, one per asset class.

The wall template (tools/wall_template_map.py) exists because the renderer's
grammar is invisible from an image editor. Every other class has the same
problem in a smaller way: a mob sheet's rows are Up/Right/Down/Left and not
the order anyone guesses, a splat's 21 cells each have a required alpha shape,
an object is bottom-anchored except when it is top-anchored. So each class gets
the same treatment: a canvas at the exact shipped size, every cell labelled
with what goes in it, and the rules written next to it.

These are drawing guides AND generator prompts -- hand the PNG to an image
model together with the brief from `docs/ASSET_PIPELINE.md` and it composes
into the right cells instead of into a nice picture that the engine then
shreds.

    python3 tools/asset_templates.py                  # all classes
    python3 tools/asset_templates.py --class mob      # one
    python3 tools/asset_templates.py --list

Writes build/qa/template-<class>.png and copies them to docs/references/.

Every dimension and cell meaning below is cited to the file it was verified
in; nothing here is asserted from memory. The wall class is not duplicated --
it is generated by wall_template_map.py, which derives its cell roles by
enumerating the engine port.
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_QA = os.path.join(REPO, "build", "qa")
OUT_DOCS = os.path.join(REPO, "docs", "references")

BG = (24, 24, 30, 255)
GRID = (255, 255, 255, 90)
CO_A = (60, 160, 255)
CO_B = (255, 170, 60)
CO_C = (120, 235, 205)
CO_D = (200, 70, 220)
CO_WARN = (235, 60, 60)


def fonts():
    try:
        return (ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 14),
                ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 12),
                ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", 18))
    except OSError:
        f = ImageFont.load_default()
        return f, f, f


def canvas(art_w, art_h, legend_w, text_h, zoom, reference=None):
    """Checkerboard art area + legend column + rules strip."""
    img = Image.new("RGBA", (art_w * zoom + legend_w, art_h * zoom + text_h), BG)
    checker = Image.new("RGBA", (art_w * zoom, art_h * zoom), (46, 46, 56, 255))
    cd = ImageDraw.Draw(checker)
    for y in range(0, art_h * zoom, 16):
        for x in range(0, art_w * zoom, 16):
            if ((x + y) // 16) % 2 == 0:
                cd.rectangle((x, y, x + 15, y + 15), fill=(58, 58, 70, 255))
    img.alpha_composite(checker, (0, 0))
    if reference is not None and os.path.exists(reference):
        ref = Image.open(reference).convert("RGBA")
        if ref.size == (art_w, art_h):
            img.alpha_composite(ref.resize((art_w * zoom, art_h * zoom), Image.NEAREST), (0, 0))
    return img


def tint(img, box, colour, alpha=52):
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    ImageDraw.Draw(layer).rectangle(box, fill=colour + (alpha,))
    img.alpha_composite(layer)


def write_block(d, x, y, lines, font, colour=(225, 225, 230), step=20):
    for line in lines:
        d.text((x, y), line, fill=colour, font=font)
        y += step
    return y


def finish(img, d, title, legend, rules, art_w, art_h, zoom, font, font_big):
    lx = art_w * zoom + 16
    d.text((lx, 10), title, fill=(255, 255, 255), font=font_big)
    write_block(d, lx, 40, legend, font)
    write_block(d, 14, art_h * zoom + 12, rules, font)


