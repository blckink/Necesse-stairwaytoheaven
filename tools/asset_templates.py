# tile: the _splat atlas

def template_splat(variants=4):
    """224 x 96*variants. Cell map VERIFIED in docs/research/splat-format.md 5.3,
    which was cross-checked against dirt/snow/ash _splat by per-cell alpha."""
    zoom = 4
    art_w, art_h = 224, 96 * variants
    img = canvas(art_w, art_h, 700, 480, zoom,
                 os.path.join(REPO, "src/main/resources/tiles/cloudturf_splat.png"))
    d = ImageDraw.Draw(img)
    font, font_sm, font_big = fonts()
    # (col,row) -> (short, long)
    CELLS = {
        (3, 0): ("FULL 1", "plain tile\n+ ITEM ICON"), (4, 0): ("FULL 2", "plain tile"),
        (5, 0): ("FULL 3", "plain tile"), (6, 0): ("FULL 4", "plain tile"),
        (1, 1): ("all 4", "opaque\nall edges"),
        (1, 0): ("S", "opaque\nBOTTOM"), (1, 2): ("N", "opaque\nTOP"),
        (2, 1): ("W", "opaque\nLEFT"), (0, 1): ("E", "opaque\nRIGHT"),
        (3, 1): ("N+W", "cut SE\nquadrant"), (4, 1): ("N+E", "cut SW"),
        (3, 2): ("S+W", "cut NE"), (4, 2): ("E+S", "cut NW"),
        (5, 1): ("N+E+W", "thin at\nbottom"), (6, 1): ("N+E+S", "thin at\nleft"),
        (5, 2): ("E+S+W", "thin at\ntop"), (6, 2): ("N+S+W", "thin at\nright"),
        (0, 0): ("diag SE", "blob, notch\nat NW"), (2, 0): ("diag SW", "blob, notch\nat NE"),
        (0, 2): ("diag NE", "blob, notch\nat SW"), (2, 2): ("diag NW", "blob, notch\nat SE"),
    }
    for v in range(variants):
        oy = v * 96 * zoom
        for (cx, cy), (short, long) in CELLS.items():
            x0, y0 = cx * 32 * zoom, oy + cy * 32 * zoom
            box = (x0, y0, x0 + 32 * zoom - 1, y0 + 32 * zoom - 1)
            tint(img, box, CO_C if cx >= 3 and cy == 0 else CO_A, 46)
            d.rectangle(box, outline=GRID)
            if v == 0:
                d.text((x0 + 4, y0 + 3), short, fill=(255, 255, 255), font=font)
                yy = y0 + 22
                for line in long.split("\n"):
                    d.text((x0 + 4, yy), line, fill=(235, 235, 240), font=font_sm)
                    yy += 14
        d.rectangle((0, oy, art_w * zoom - 1, oy + 96 * zoom - 1),
                    outline=CO_D, width=3)
        d.text((6, oy + 96 * zoom - 22), "variant %d (whole 224x96 block)" % v,
               fill=(255, 200, 255), font=font)
    finish(img, d, "TERRAIN _splat ATLAS  224 x 96*variants",
           ["7x3 cells of 32px = one 224x96 BLOCK.",
            "Stack one block per variant, downward.",
            "Shipped grounds use 5-6 variants.",
            "",
            "The four cyan FULL cells are the tile you",
            "actually see most of the time. (3,0) is",
            "ALSO the item icon the game generates.",
            "",
            "Every other cell is a BLEND piece: the",
            "same material, with alpha cut to the shape",
            "named in it, so this ground fades into the",
            "one beside it.",
            "",
            "N/E/S/W in a cell name = which neighbours",
            "are the same ground; the OPAQUE part faces",
            "those neighbours.",
            "",
            "Liquids need this too (224*frames wide)."],
           ["THE TWO RULES THAT DECIDE WHETHER IT LOOKS VANILLA (tools/tile_behaviour_audit.py enforces both):",
            "1. The tone unit is a 2x2 PIXEL BLOCK, never a lone pixel. Vanilla is 100% coherent on that grid.",
            "2. Texture comes from MANY QUIET steps, not few loud ones: mean |dRGB| from the modal colour 7-27,",
            "   density 280-620 non-modal px per 32x32 cell. Vanilla carries a whole grass texture in five RGB levels.",
            "",
            "Draw ONE seamless 32x32 material first. Everything else is that material with alpha cut to shape."],
           art_w, art_h, zoom, font, font_big)
    return img, "splat"


